import PDFDocument from "pdfkit"

export const generatePdf = (data) =>
    new Promise((resolve, reject) => {
        try {
            const doc = new PDFDocument({
                size: "A4",
                margin: 50,
                info: {
                    Author: "CortexAI",
                    Title: data?.title || "Document",
                    Creator: "CortexAI"
                }
            })

            const chunks = []
            doc.on("data", (chunk) => chunks.push(chunk))
            doc.on("end", () => resolve(Buffer.concat(chunks)))
            doc.on("error", reject)

            // title (set the color BEFORE the text)
            doc
                .font("Helvetica-Bold")
                .fontSize(28)
                .fillColor("#111827")
                .text(String(data?.title || "Document"), { align: "center" })

            // subtitle
            if (data?.subtitle) {
                doc.moveDown(0.5)
                doc
                    .font("Helvetica")
                    .fontSize(12)
                    .fillColor("#6B7280")
                    .text(String(data.subtitle), { align: "center" })
            }

            doc.moveDown(2)

            for (const s of data?.sections ?? []) {
                // do not leave a heading alone at the bottom of a page
                if (doc.y > doc.page.height - doc.page.margins.bottom - 100) {
                    doc.addPage()
                }

                if (s?.heading) {
                    doc
                        .font("Helvetica-Bold")
                        .fontSize(18)
                        .fillColor("#111827")
                        .text(String(s.heading))
                    doc.moveDown(0.5)
                }

                for (const p of s?.points ?? []) {
                    doc
                        .font("Helvetica")
                        .fontSize(12)
                        .fillColor("#374151")
                        .text("• " + String(p), { lineGap: 5 })
                }

                doc.moveDown()
            }

            // footer
            doc.moveDown()
            doc
                .font("Helvetica")
                .fontSize(10)
                .fillColor("#9CA3AF")
                .text("Generated By CortexAI", { align: "center" })

            doc.end()
        } catch (err) {
            reject(err)
        }
    })